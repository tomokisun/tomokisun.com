const byId = new Map(apps.map((app) => [app.id, app]))

export function findApp(id: string): AppDef | undefined {
  return byId.get(id)
}

export function appName(id: string): string {
  return byId.get(id)?.name ?? id
}

export const pcApps = apps.filter((app) => !app.platforms || app.platforms.includes('pc'))
export const spApps = apps.filter((app) => !app.platforms || app.platforms.includes('sp'))
export const desktopApps = pcApps.filter((app) => app.desktop)
export const dockApps = pcApps.filter((app) => app.dock)
export const spDockApps = spApps.filter((app) => app.spDock)

/** SPホーム画面のページ数（App Libraryはこの後ろに1枚足される） */
export const SP_HOME_PAGES = 3

export function spHomePage(page: number): AppDef[] {
  return spApps.filter((app) => app.page === page)
}

/** カテゴリ順に並べた一覧（Launchpad / App Library用） */
export function appsByCategory(list: AppDef[]): [AppCategory, AppDef[]][] {
  const order: AppCategory[] = ['system', 'work', 'social', 'media', 'life', 'dev', 'fun']
  return order
    .map((category) => [category, list.filter((app) => app.category === category)] as [AppCategory, AppDef[]])
    .filter(([, group]) => group.length > 0)
}

/** ウィンドウの初期位置。geometry未指定のアプリは登録順にカスケードさせる */
export function windowGeometry(app: AppDef, index: number): WindowGeometry {
  if (app.geometry) return app.geometry
  return { top: 64 + (index % 8) * 24, left: 220 + (index % 10) * 28, width: 440 }
}
