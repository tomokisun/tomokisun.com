export type WindowGeometry = { top: number; left: number; width: number; height?: number }

export type AppDef = {
  id: string
  /** ホーム画面・Dock・Launchpadでの名前 */
  name: string
  /** PCウィンドウのタイトル（省略時は name。macOS側だけ堅い名前になるアプリがある） */
  windowTitle?: string
  icon: string
  color: OsColor
  category: AppCategory
  /** Spotlight／Launchpad／App Libraryに出る一言。ここに小ネタを仕込む */
  subtitle: string
  /** PCウィンドウのステータスバー */
  statusBar?: string
  /** 動く画面。省略時は両方 */
  platforms?: ('pc' | 'sp')[]
  /** PCデスクトップにアイコンを置く */
  desktop?: boolean
  /** PCのDockに常駐させる */
  dock?: boolean
  /** SPのドックに常駐させる */
  spDock?: boolean
  /** SPホーム画面の何ページ目に置くか（未指定はApp Libraryのみ＝「持ってはいるが出していない」） */
  page?: number
  /** PCウィンドウの初期位置。未指定なら登録順のカスケード配置 */
  geometry?: WindowGeometry
  /** SPのジグル編集で削除しようとしたときの拒否理由 */
  removeRefusal?: string
  /** Spotlightのための別名 */
  keywords?: string[]
}

